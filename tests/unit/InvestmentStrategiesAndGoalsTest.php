<?php

declare(strict_types=1);

namespace Tests\Unit;

use App\Modules\User\Controllers\InvestmentsController;
use App\Modules\User\Controllers\InvestmentController;
use App\Modules\APIs\Controllers\APIController;
use App\Modules\APIs\Controllers\ManagementAPIController;
use App\Modules\APIs\Controllers\MarketingAPIController;
use App\Modules\APIs\Controllers\AlertsAPIController;
use CodeIgniter\Test\CIUnitTestCase;
use ReflectionClass;

/**
 * @internal
 */
final class InvestmentStrategiesAndGoalsTest extends CIUnitTestCase
{
    public function testInvestmentsControllerHasFullStrategyAndGoalMethodContract(): void
    {
        $rc = new ReflectionClass(InvestmentsController::class);

        $expectedMethods = [
            'getStrategies',
            'getStrategy',
            'createStrategy',
            'updateStrategy',
            'deleteStrategy',
            'getGoals',
            'getGoal',
            'createGoal',
            'updateGoal',
            'deleteGoal',
        ];

        foreach ($expectedMethods as $method) {
            $this->assertTrue(
                $rc->hasMethod($method),
                "InvestmentsController must implement method {$method}"
            );
        }
    }

    public function testInvestmentControllerAliasInheritsAllMethods(): void
    {
        $this->assertTrue(
            is_subclass_of(InvestmentController::class, InvestmentsController::class),
            'InvestmentController must extend InvestmentsController for backward compatibility'
        );

        $rc = new ReflectionClass(InvestmentController::class);
        $this->assertTrue($rc->hasMethod('getStrategies'));
        $this->assertTrue($rc->hasMethod('getGoals'));
    }

    public function testAPIControllerHasRequiredSymbolsMethodContract(): void
    {
        $rc = new ReflectionClass(APIController::class);

        $this->assertTrue($rc->hasMethod('getSymbolsByTradeType'));
        $this->assertTrue($rc->hasMethod('status'));
        $this->assertTrue($rc->hasMethod('index'));

        $controller = new APIController();
        $response = $controller->getSymbolsByTradeType('crypto');
        $body = json_decode((string) $response->getBody(), true);

        $this->assertSame('success', $body['status']);
        $this->assertSame('crypto', $body['trade_type']);
        $this->assertContains('SOL', $body['symbols']);
    }

    public function testManagementAndMarketingAPIControllersHaveRequiredContractMethods(): void
    {
        $mgmtRc = new ReflectionClass(ManagementAPIController::class);
        $this->assertTrue($mgmtRc->hasMethod('fetchLatestSummaries'));
        $this->assertTrue($mgmtRc->hasMethod('triggerPostAutogenOnEmpty'));

        $mktgRc = new ReflectionClass(MarketingAPIController::class);
        $expectedMktgMethods = [
            'getSocialPlatforms',
            'getSocialCommunities',
            'saveSocialCommunity',
            'getPostTemplates',
            'savePostTemplate',
            'generatePlatformPosts',
            'generateDailyCommunityPosts',
            'exportGeneratedPostJson',
            'generateRevenueDocs',
            'cronGenerateDailyCommunityPosts',
            'cronQueueDistribution',
        ];

        foreach ($expectedMktgMethods as $method) {
            $this->assertTrue(
                $mktgRc->hasMethod($method),
                "MarketingAPIController must implement method {$method}"
            );
        }

        $alertsRc = new ReflectionClass(AlertsAPIController::class);
        $this->assertTrue($alertsRc->hasMethod('fetchAutoGeneratedAnalysis'));
        $this->assertTrue($alertsRc->hasMethod('generateNow'));
        $this->assertTrue($alertsRc->hasMethod('updateStatus'));
    }
}
