    public function testDuplicateActiveAlertPrevention(): void
    {
        $first = $this->alertService->createTradeAlert([
            'ticker'      => 'NVDA',
            'entry_price' => 120.00,
        ], self::USER_A);
        $this->assertSame('success', $first['status']);

        // Second creation for same symbol while first is still Opened
        $second = $this->alertService->createTradeAlert([
            'ticker'      => 'NVDA',
            'entry_price' => 125.00,
        ], self::USER_A);

        $this->assertSame('duplicate', $second['status']);
        $this->assertTrue($second['duplicate']);
        $this->assertSame($first['trade_id'], $second['trade_id']);
    }

    public function testEvaluateAlertTriggersTargetHit(): void
    {
        $created = $this->alertService->createTradeAlert([
            'ticker'       => 'TSLA',
            'entry_price'  => 250.00,
            'target_price' => 260.00,
            'stop_loss'    => 240.00,
        ], self::USER_A);

        $eval = $this->alertService->evaluateAlert($created['trade_id'], 262.50);

        $this->assertSame('success', $eval['status']);
        $this->assertSame('TARGET_HIT', $eval['evaluation']);
        $this->assertSame('Target Hit', $eval['new_status']);
        $this->assertTrue($eval['updated']);

        // Verify database row updated
        $db = db_connect();
        $row = $db->table('bf_investment_trade_alerts')
            ->where('id', $created['trade_id'])
            ->limit(1)
            ->get()
            ->getRowArray();
        $this->assertSame('Target Hit', $row['status']);
    }

