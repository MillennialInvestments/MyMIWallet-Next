    private function createAlertsController(int $userId): AlertsController
    {
        $request = new IncomingRequest(config('App'), new URI('http://example.com/Alerts'), null, new UserAgent());
        $response = new Response(config('App'));
        $logger = Services::logger();

        $controller = new AlertsController();
        $controller->initController($request, $response, $logger);

        $ref = new ReflectionClass($controller);
        $prop = $ref->getProperty('cuID');
        $prop->setAccessible(true);
        $prop->setValue($controller, $userId);

        return $controller;
    }

    private function createAlertsAPIController(array $post = []): AlertsAPIController
    {
        $request = new class ($post) extends IncomingRequest {
            public function __construct(private array $mockPost)
            {
                parent::__construct(config('App'), new URI('http://example.com/API/Alerts'), null, new UserAgent());
            }

            public function getPost($index = null, $filter = null, $flags = null)
            {
                if ($index === null) {
                    return $this->mockPost;
                }
                return $this->mockPost[$index] ?? null;
            }
        };

        $response = new Response(config('App'));
        $logger = Services::logger();

        $controller = new AlertsAPIController();
        $controller->initController($request, $response, $logger);

        return $controller;
    }
