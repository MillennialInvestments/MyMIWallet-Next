    public function testCreateTradeAlertSuccessWithCalculatedTargets(): void
    {
        $res = $this->alertService->createTradeAlert([
            'ticker'      => 'aapl',
            'entry_price' => 200.00,
            'category'    => 'Active Buy Alert',
        ], self::USER_A);

        $this->assertSame('success', $res['status']);
        $this->assertFalse($res['duplicate']);
        $this->assertGreaterThan(0, $res['trade_id']);
        $this->assertSame('AAPL', $res['symbol']);

        $data = $res['data'];
        $this->assertEqualsWithDelta(200.00, $data['entry_price'], 0.01);
        $this->assertEqualsWithDelta(206.00, $data['target_price'], 0.01, 'Target should auto-calculate +3% gain');
        $this->assertEqualsWithDelta(196.00, $data['stop_loss'], 0.01, 'Stop loss should auto-calculate -2% loss');
        $this->assertSame(self::USER_A, $data['created_by']);
        $this->assertSame('Opened', $data['status']);

        // Verify history row was recorded
        $db = db_connect();
        $history = $db->table('bf_investment_alert_history')
            ->where('trade_alert_id', $res['trade_id'])
            ->limit(1)
            ->get()
            ->getRowArray();

        $this->assertNotNull($history);
        $this->assertSame('AAPL', $history['ticker']);
        $this->assertSame(self::USER_A, (int) $history['user_id']);
    }

