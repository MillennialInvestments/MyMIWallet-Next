    public function testEvaluateActiveAlertsBatchExecution(): void
    {
        $a1 = $this->alertService->createTradeAlert(['ticker' => 'META', 'entry_price' => 500, 'target_price' => 520, 'stop_loss' => 480], self::USER_A);
        $a2 = $this->alertService->createTradeAlert(['ticker' => 'GOOGL', 'entry_price' => 170, 'target_price' => 175, 'stop_loss' => 165], self::USER_A);

        // Preload fresh market snapshot for META reaching target
        $db = db_connect();
        $db->table('bf_market_snapshots')->insert([
            'symbol'     => 'META',
            'price'      => 525.00,
            'created_at' => date('Y-m-d H:i:s'),
        ]);

        $batch = $this->alertService->evaluateActiveAlerts(10);

        $this->assertSame(2, $batch['evaluated_count']);
        $this->assertSame(1, $batch['targets_hit']);
    }

    public function testDeliverAlertDryRunAndPersistedDeliveryState(): void
    {
        $created = $this->alertService->createTradeAlert([
            'ticker'      => 'NFLX',
            'entry_price' => 600.00,
        ], self::USER_A);

        $res = $this->alertService->deliverAlert($created['trade_id'], ['discord', 'email'], true);

        $this->assertSame('success', $res['status']);
        $this->assertTrue($res['dry_run']);
        $this->assertTrue($res['channels']['discord']['success']);
        $this->assertSame('dry_run', $res['channels']['discord']['mode']);

        // Check persisted delivery flags
        $db = db_connect();
        $row = $db->table('bf_investment_trade_alerts')
            ->where('id', $created['trade_id'])
            ->limit(1)
            ->get()
            ->getRowArray();

        $this->assertSame(1, (int) $row['send_alert']);
        $this->assertSame(1, (int) $row['alert_sent']);
        $this->assertSame(1, (int) $row['notification_sent']);
    }

    public function testUserScopedAlertHistoryAndIDORIsolation(): void
    {
        // Create alert and history for User A
        $this->alertService->createTradeAlert(['ticker' => 'DIS', 'entry_price' => 100.00], self::USER_A);

        // Create alert and history for User B
        $this->alertService->createTradeAlert(['ticker' => 'SONY', 'entry_price' => 80.00], self::USER_B);

        $historyA = $this->alertService->getUserAlertHistory(self::USER_A);
        $historyB = $this->alertService->getUserAlertHistory(self::USER_B);

        $this->assertCount(1, $historyA);
        $this->assertSame('DIS', $historyA[0]['ticker']);

        $this->assertCount(1, $historyB);
        $this->assertSame('SONY', $historyB[0]['ticker']);

        // Filtering by ticker
        $filtered = $this->alertService->getUserAlertHistory(self::USER_A, ['ticker' => 'NONEXISTENT']);
        $this->assertEmpty($filtered);
    }

    public function testAlertsControllerViewAlertRedirectsWhenUnsent(): void
    {
        $created = $this->alertService->createTradeAlert(['ticker' => 'UBER', 'entry_price' => 70.00], self::USER_A);

        $controller = $this->createAlertsController(self::USER_A);
        $response = $controller->viewAlert($created['trade_id']);

        // Since send_alert is 0, viewAlert must redirect to /Alerts with error
        $this->assertInstanceOf(\CodeIgniter\HTTP\RedirectResponse::class, $response);
        $this->assertContains($response->getStatusCode(), [301, 302]);
        $this->assertStringContainsString('Alerts', $response->getHeaderLine('Location'));
    }

    public function testAlertsControllerGetUserAlertsReturnsJson(): void
    {
        $created = $this->alertService->createTradeAlert(['ticker' => 'PLTR', 'entry_price' => 30.00], self::USER_A);
        $this->alertService->deliverAlert($created['trade_id'], ['email'], true);

        $controller = $this->createAlertsController(self::USER_A);
        $response = $controller->getUserAlerts();

        $this->assertSame(200, $response->getStatusCode());
        $body = json_decode($response->getBody(), true);
        $this->assertSame('success', $body['status']);
    }

    public function testAlertsAPIControllerEndpoints(): void
    {
        $created = $this->alertService->createTradeAlert(['ticker' => 'COIN', 'entry_price' => 220.00], self::USER_A);

        $apiController = $this->createAlertsAPIController(['trade_id' => $created['trade_id'], 'status' => 'Closed']);

        // 1. updateStatus
        $resUpdate = $apiController->updateStatus($created['trade_id'], 'Closed');
        $this->assertSame(200, $resUpdate->getStatusCode());
        $bodyUpdate = json_decode($resUpdate->getBody(), true);
        $this->assertSame('success', $bodyUpdate['status']);
        $this->assertSame('Closed', $bodyUpdate['new_status']);

        // 2. research
        $resResearch = $apiController->research();
        $this->assertSame(200, $resResearch->getStatusCode());
        $bodyResearch = json_decode($resResearch->getBody(), true);
        $this->assertSame('success', $bodyResearch['status']);

        // 3. generateNow
        $resGen = $apiController->generateNow();
        $this->assertSame(200, $resGen->getStatusCode());
        $bodyGen = json_decode($resGen->getBody(), true);
        $this->assertSame('success', $bodyGen['status']);
    }

